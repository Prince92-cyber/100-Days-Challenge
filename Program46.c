/* Write a program to print the following pattern:
*****
*****
*****
*****
*****
*/
#include <stdio.h>
int main()
{
// Using Nested Looping to print the required pattern...
for(int i=1;i<=5;i++)
{
for(int j=1;j<=5;j++)
{
printf("* ");
}
printf("\n");
}
}
// Program is finished successfully...
